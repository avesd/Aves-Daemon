import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { applyReleases } from "../release-apply.ts";
import { createChangeset } from "../release-notes.ts";
import { planReleases } from "../release-plan.ts";

test("Client and Worker releases consume shared notes independently and record the largest bump", (t) => {
    const root = mkdtempSync(join(tmpdir(), "avesd-worker-release-"));
    t.after(() => rmSync(root, { recursive: true, force: true }));
    const target = "server/worker";
    mkdirSync(join(root, target), { recursive: true });
    const manifest = join(root, target, "version.json");
    writeFileSync(manifest, '{"version":"0.0.0"}');
    const client = "apps/macos";
    mkdirSync(join(root, client), { recursive: true });
    const clientManifest = join(root, client, "version.json");
    writeFileSync(clientManifest, '{"version":"1.0.0"}');
    const shared = createChangeset(root, { [client]: "patch", [target]: "patch" }, "Update both components.", "shared");
    applyReleases(planReleases(root, client));
    assert.equal(JSON.parse(readFileSync(clientManifest, "utf8")).version, "1.0.1");
    assert.equal(JSON.parse(readFileSync(manifest, "utf8")).version, "0.0.0");
    assert.equal(existsSync(shared), true);
    assert.equal(planReleases(root, client).changes.length, 0);
    const first = createChangeset(root, { [target]: "minor" }, "Add snapshots.", "snapshots");
    const second = createChangeset(root, { [target]: "patch" }, "Handle empty cells.", "empty");
    const plan = planReleases(root);
    assert.equal(plan.changes[0]?.nextVersion, "0.1.0");
    assert.equal(JSON.parse(readFileSync(manifest, "utf8")).version, "0.0.0");
    applyReleases(plan);
    assert.equal(JSON.parse(readFileSync(manifest, "utf8")).version, "0.1.0");
    assert.equal(existsSync(shared), false);
    assert.equal(JSON.parse(readFileSync(clientManifest, "utf8")).version, "1.0.1");
    assert.equal(existsSync(first) || existsSync(second), false);
    assert.throws(() => applyReleases(plan));
    const after = planReleases(root);
    assert.equal(after.changes.length, 0);
    const [history] = Object.values(after.ledgers[0]!.quarters);
    assert.deepEqual(history!.entries["0.1.0"]!.intents, ["empty", "shared", "snapshots"]);
    assert.match(history!.changelog, /Add snapshots\./);
    assert.match(history!.changelog, /Handle empty cells\./);
});
