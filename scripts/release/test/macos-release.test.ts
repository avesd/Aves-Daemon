import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { applyReleases } from "../release-apply.ts";
import { createChangeset } from "../release-notes.ts";
import { planReleases } from "../release-plan.ts";

test("The macOS release consumes pending notes and records the largest bump", (t) => {
    const root = mkdtempSync(join(tmpdir(), "avesd-macos-release-"));
    t.after(() => rmSync(root, { recursive: true, force: true }));
    const target = "apps/macos";
    mkdirSync(join(root, target), { recursive: true });
    const manifest = join(root, target, "version.json");
    writeFileSync(manifest, '{"version":"0.0.0"}');
    const first = createChangeset(root, { [target]: "minor" }, "Add event previews.", "previews");
    const second = createChangeset(root, { [target]: "patch" }, "Show each callsign once.", "callsign");
    const plan = planReleases(root);
    assert.equal(plan.changes[0]?.nextVersion, "0.1.0");
    assert.equal(JSON.parse(readFileSync(manifest, "utf8")).version, "0.0.0");
    applyReleases(plan);
    assert.equal(JSON.parse(readFileSync(manifest, "utf8")).version, "0.1.0");
    assert.equal(existsSync(first) || existsSync(second), false);
    assert.throws(() => applyReleases(plan));
    const after = planReleases(root);
    assert.equal(after.changes.length, 0);
    const [history] = Object.values(after.ledgers[0]!.quarters);
    assert.deepEqual(history!.entries["0.1.0"]!.intents, ["callsign", "previews"]);
    assert.match(history!.changelog, /Add event previews\./);
    assert.match(history!.changelog, /Show each callsign once\./);
});
